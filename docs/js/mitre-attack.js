// ===== MITRE ATT&CK FUNCTIONS =====

const PLATFORMS = {
    enterprise: ["Windows", "Linux", "macOS", "Network", "PRE", "Containers", "Office 365", "SaaS", "Google Workspace", "IaaS", "Azure AD"],
    mobile: ["Android", "iOS"],
    ics: ["None"],
};

const HEAT_GRADIENT = ["#ffe766ff", "#ff9558", "#ff6666ff"];

// Sum link weights per target, keep those matching `accept`, and bubble sub-technique scores up to their parent
function techniqueScores(accept, parentOf) {
    const scores = {};
    for (const link of App.graph.links) {
        if (accept(link.target)) scores[link.target] = (scores[link.target] || 0) + link.value;
    }
    for (const [id, score] of Object.entries({ ...scores })) {
        const parent = parentOf(id);
        if (parent) scores[parent] = (scores[parent] || 0) + score;
    }
    return scores;
}

function navigatorLayer(overrides) {
    return {
        "sorting": 3,
        "layout": {
            "layout": "side",
            "aggregateFunction": "average",
            "showID": false,
            "showName": true,
            "showAggregateScores": false,
            "countUnscored": false,
            "expandedSubtechniques": "none"
        },
        "hideDisabled": false,
        "techniques": [],
        "legendItems": [],
        "metadata": [],
        "links": [],
        "showTacticRowBackground": false,
        "tacticRowBackground": "#dddddd",
        "selectTechniquesAcrossTactics": true,
        "selectSubtechniquesWithParent": true,
        "selectVisibleTechniques": false,
        ...overrides,
    };
}

function create_mitre_layer(techniquesDb) {
    const domain = App.mode === 'enterprise-defend' ? 'enterprise' : App.mode;
    const scores = techniqueScores(
        id => kindOf(id) === 'ATTACK',
        id => /^T\d+\.\d+$/.test(id) ? id.split('.')[0] : null
    );
    const maxScore = Math.max(0, ...Object.values(scores));

    const layer = navigatorLayer({
        "name": "CVE2CAPEC - New CVEs layer",
        "versions": { "attack": "20", "navigator": "5.3.2", "layer": "4.5" },
        "domain": domain + "-attack",
        "description": `Generated by CVE2CAPEC from ${App.lastCves.length} CVEs`,
        "filters": { "platforms": PLATFORMS[domain] },
        "gradient": { "colors": HEAT_GRADIENT, "minValue": 0, "maxValue": maxScore },
    });

    for (const [id, score] of Object.entries(scores)) {
        for (const tactic of techniquesDb[id] || []) {
            const row = {
                "techniqueID": id,
                "tactic": tactic.toLowerCase().replaceAll(' ', '-'),
                "color": "",
                "comment": "",
                "enabled": true,
                "metadata": [],
                "links": [],
                "showSubtechniques": false
            };
            if (score > 0) row.score = score;
            layer.techniques.push(row);
        }
    }

    safeStorageSet('layer', JSON.stringify(layer));
    return layer;
}

function layerStats(layer) {
    const unique = new Set();
    let hits = 0;
    for (const t of layer?.techniques || []) {
        if (t.score > 0 && !unique.has(t.techniqueID)) {
            unique.add(t.techniqueID);
            hits += t.score;
        }
    }
    return { techniques: unique.size, hits };
}

function updateAttackStats() {
    const { techniques, hits } = layerStats(App.layers.attack);
    $('#attack-stats').textContent = `${plural(techniques, 'technique')} affected · ${plural(hits, 'hit')}`;
    $('#attack-tab-count').textContent = techniques || '';
}

// Mount a Navigator build in an iframe. It reads its layer from localStorage on boot.
function mountNavigator({ id, src, host, onReady }) {
    document.getElementById(id)?.remove();
    const iframe = document.createElement('iframe');
    iframe.src = src;
    iframe.id = id;
    iframe.title = id === 'mitre' ? 'MITRE ATT&CK Navigator' : 'MITRE ATLAS Navigator';
    iframe.allowFullscreen = true;
    iframe.loading = 'eager';
    document.getElementById(host).appendChild(iframe);
    iframe.addEventListener('load', () => {
        try {
            const doc = iframe.contentWindow.document;
            const style = doc.createElement('style');
            // Tone the Navigator chrome down to match the host page
            style.textContent = `
                body { font-family: Inter, Roboto, system-ui, sans-serif; }
                .help-header .js-toggle-fullscreen-btn { display: none; }
            `;
            doc.head.appendChild(style);
            onReady?.(doc);
        } catch (e) {
            console.warn('Navigator iframe not accessible', e);
        }
    });
    return iframe;
}

function print_mitre() {
    if (!App.layers.attack) return;
    mountNavigator({ id: 'mitre', src: 'mitre/', host: 'frame' });
}
